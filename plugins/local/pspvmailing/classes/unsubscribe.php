namespace local_pspvmailing;

/**
 * Opting out of commercial communications, with a link that needs no login.
 *
 * The link carries the id of the user and a token only this site can compute, so nobody can
 * unsubscribe somebody else by guessing.
 *
 * @package    local_pspvmailing
 * @copyright  2026 Soportic <https://soportic.es>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class unsubscribe {
    /**
     * Token that proves a link was generated by this site for a user.
     *
     * @param int $userid
     * @return string
     */
    public static function token(int $userid): string {
        $secret = (string) get_config('local_pspvmailing', 'secret');
        if ($secret === '') {
            $secret = random_string(64);
            set_config('secret', $secret, 'local_pspvmailing');
        }
        return hash_hmac('sha256', 'unsubscribe:' . $userid, $secret);
    }

    /**
     * Whether a token is the one of a user.
     *
     * @param int $userid
     * @param string $token
     * @return bool
     */
    public static function verify(int $userid, string $token): bool {
        return $userid > 0 && hash_equals(self::token($userid), $token);
    }

    /**
     * The link a user unsubscribes with.
     *
     * @param int $userid
     * @return \core\url
     */
    public static function url(int $userid): \core\url {
        return new \core\url('/local/pspvmailing/unsubscribe.php', ['u' => $userid, 't' => self::token($userid)]);
    }

    /**
     * Whether a user has opted out.
     *
     * @param int $userid
     * @return bool
     */
    public static function is_opted_out(int $userid): bool {
        global $DB;

        return $DB->record_exists('local_pspvmailing_optout', ['userid' => $userid]);
    }

    /**
     * Records that a user does not want commercial communications. Safe to call twice.
     *
     * @param int $userid
     */
    public static function opt_out(int $userid): void {
        global $DB;

        if (self::is_opted_out($userid)) {
            return;
        }
        $id = $DB->insert_record('local_pspvmailing_optout', ['userid' => $userid, 'timecreated' => time()]);
        event\user_unsubscribed::create([
            'context' => \core\context\system::instance(),
            'objectid' => $id,
            'relateduserid' => $userid,
        ])->trigger();
    }

    /**
     * A user who had opted out wants the communications again.
     *
     * @param int $userid
     */
    public static function opt_in(int $userid): void {
        global $DB;

        $DB->delete_records('local_pspvmailing_optout', ['userid' => $userid]);
    }
}
